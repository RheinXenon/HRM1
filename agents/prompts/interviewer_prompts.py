ANSWER_EVALUATION_PROMPT = """请评估候选人的回答质量，特别注意识别**过度自信**和**不懂装懂**的信号。

问题: {question}
候选人回答: {answer}
考察技能: {target_skills}

评估维度:
1. 回答的完整性和相关性
2. 技术深度和准确性
3. 实际经验的体现
4. 表达的清晰度
5. 问题解决能力的展现

**重点关注以下过度自信信号：**
- 使用高级术语（如"微服务"、"分布式"、"高并发"）但缺乏具体细节
- 回答模糊、使用大量不确定词汇（"一般"、"差不多"、"应该"、"可能"）
- 主动承认"记不清"、"不太熟"但仍给出笼统回答
- 提到技术概念但没有具体数据、指标或代码示例
- 回答过短（<150字）但谈论复杂话题
- 缺乏对技术方案trade-off的深入思考
- 无法给出实际项目中的具体问题和解决方案

**评分指导原则：**
- 如果回答显示深度理解+具体经验：8-10分
- 如果回答合理但缺少深度：6-7分
- 如果回答显示基本理解但细节不足：4-5分
- 如果回答空洞、模糊或明显不懂装懂：1-3分

请以JSON格式返回评估结果，必须包含以下字段：
{{
  "score": 总体评分数字(1-10),
  "feedback": "各维度的具体反馈文字，明确指出回答的优势和不足",
  "confidence_level": "评估候选人的真实信心程度：genuine（真懂）、uncertain（不确定）、overconfident（过度自信/不懂装懂）",
  "detail_score": 细节丰富度评分数字(1-10),
  "need_follow_up": "yes或no",
  "follow_up_direction": "追问建议：如果怀疑过度自信，明确指出需要追问的技术点"
}}

重要要求：
1. 字段名（keys）必须使用英文，如上所示
2. feedback 和 follow_up_direction 的内容必须用中文书写
3. score 和 detail_score 必须是1-10之间的数字
4. confidence_level 必须是 "genuine"、"uncertain" 或 "overconfident" 之一
5. 如果 confidence_level 是 "overconfident"，need_follow_up 应该设为 "yes"
"""

FOLLOW_UP_PROMPT = """基于候选人的回答，生成一个深入追问的问题，以验证其真实能力水平。

原问题: {original_question}
候选人回答: {answer}
评估反馈: {evaluation}
追问目标技能: {target_skill}

**追问策略：**
1. **要求具体化**：如果候选人提到技术概念，要求给出具体参数、指标、代码示例
2. **深入原理**：询问底层实现原理、工作机制、源码细节
3. **实战问题**：询问实际项目中遇到的具体问题和解决方案
4. **边界情况**：询问异常情况、性能瓶颈、容错处理
5. **技术对比**：要求对比不同方案的优劣、trade-off分析
6. **量化指标**：要求给出具体的性能数据、并发量、响应时间等

**追问问题类型示例：**
- "你提到了[技术概念]，能具体说说[具体参数/配置/实现细节]吗？"
- "这个方案在实际项目中遇到过什么性能问题？具体是怎么解决的？"
- "能画个架构图或写段伪代码来说明[技术点]吗？"
- "为什么选择[方案A]而不是[方案B]？各自的优缺点是什么？"
- "如果[极端场景]，你会怎么处理？"
- "这个优化前后的具体指标是多少？用什么工具测试的？"

要求:
- 追问必须基于候选人回答中提到的具体技术点
- 问题要能有效区分"真懂"和"不懂装懂"
- 语气专业但不刁难，像是好奇地深入讨论
- 只生成一个最有针对性的追问问题，不要解释

请直接返回追问问题文本，不要包含其他内容。
"""

FINAL_REPORT_PROMPT = """基于整场面试，生成最终评估报告。

候选人: {candidate_name}
职位: {job_title}
完整对话记录: {conversation_log}
职位要求: {job_requirements}

**重要评估原则：**

1. **追问结果权重最高**：如果对话中出现"🚩 追问后露怯"标记，说明候选人在某个技能上**过度自信/不懂装懂**，这是严重的负面信号
   - 每出现一次"追问后露怯"，推荐度应降低15-25分
   - 技能评分应以追问后的低分为准，不能被初始高分掩盖
   - 在"待改进"中必须明确指出"知识深度不足"或"过度自信"问题

2. **识别不懂装懂模式**：
   - 如果候选人初始回答得分高（7-8分），追问后降至5分以下，这表明严重的自知之明问题
   - 这类候选人即使其他方面不错，也应谨慎推荐

3. **评分一致性**：
   - 优先使用追问后的评分（如果有）
   - 不要被候选人的高级术语和表面自信所迷惑
   - 关注实际深度而非表达流畅度

4. **推荐度评分指导**：
   - 强烈推荐（90-100）：全面优秀，无明显短板，追问后依然扎实
   - 推荐（75-89）：整体合格，有亮点，追问中表现稳定
   - 观察（60-74）：基本达标但有明显不足，或出现1次追问露怯
   - 不推荐（<60）：能力不足或严重不懂装懂（出现2次及以上追问露怯）

请生成包含以下内容的评估报告，使用英文JSON字段名：
{{
  "skill_scores": {{各项技能的评分（0-10分），优先使用追问后的评分}},
  "strengths": [优势列表，3-5点],
  "improvements": [待改进方面，2-3点，必须包含追问中暴露的问题],
  "cultural_fit": "文化匹配度评估文字（考虑自知之明和诚实度）",
  "recommendation": "招聘建议（强烈推荐/推荐/观察/不推荐）",
  "recommendation_score": 推荐度数字评分0-100（严格按照上述指导原则）,
  "summary": "总结性评价（100-150字，必须提及追问结果）",
  "overconfidence_detected": true或false（是否检测到过度自信问题）
}}

重要要求：
1. JSON字段名（keys）必须使用英文，如上所示
2. 所有字段的内容值（values）必须使用中文书写
3. 包括 strengths、improvements、cultural_fit、summary 等所有文字内容都必须用中文
4. **必须严格考虑追问结果，不能忽视"追问后露怯"的负面信号**
"""
